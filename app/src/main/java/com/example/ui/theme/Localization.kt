fun localizeCategoryName(raw: String, isArabic: Boolean): String {
    if (!isArabic) return raw.ifBlank { "General" }
    return when (raw.trim().lowercase()) {
        "news" -> "أخبار"
        "sports", "sport" -> "رياضة"
        "movies", "cinema", "film" -> "أفلام"
        "kids", "children", "animation" -> "أطفال"
        "music" -> "موسيقى"
        "religious", "religion", "islamic" -> "ديني"
        "documentary", "science", "education" -> "وثائقي"
        "entertainment", "general", "variety" -> "ترفيه"
        "lifestyle", "cooking", "travel" -> "منوعات"
        "series", "drama" -> "مسلسلات"
        "comedy" -> "كوميديا"
        "business" -> "اقتصاد"
        "weather" -> "طقس"
        "classic" -> "كلاسيك"
        "undefined", "" -> "عام"
        else -> raw
    }
}
